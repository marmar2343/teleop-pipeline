"""
inspect_dataset.py

Utility for inspecting and replaying demonstrations stored in a demo.hdf5
file generated by run_teleop.py through gather_demonstrations_as_hdf5().

Usage:
    python inspect_dataset.py demonstracije/<timestamp>/demo.hdf5
    python inspect_dataset.py demonstracije/<timestamp>/demo.hdf5 --replay demo_1

Without --replay, the script prints the dataset structure and metadata,
including the number of demonstrations, their lengths, and the RoboSuite
version. This mode requires only h5py and NumPy; no robot or camera is used.

With --replay <demo_name>, the selected demonstration is visually replayed
in the RoboSuite viewer. The saved model.xml is loaded to reconstruct the
exact scene configuration used during data collection, and the recorded
simulation states are applied sequentially. This follows the same general
principle used by robomimic's playback_dataset.py.
"""

import sys
import time

import h5py
import numpy as np


def inspect(path):
    """
    Print the structure and metadata of an HDF5 demonstration dataset.

    The function reports dataset-level metadata, the number and length of
    stored demonstrations, and the first few recorded actions from the first
    demonstration.
    """
    with h5py.File(path, "r") as f:
        data = f["data"]

        print(f"File: {path}")
        print(f"Environment: {data.attrs.get('env', '?')}")
        print(f"Date: {data.attrs.get('date', '?')} {data.attrs.get('time', '?')}")
        print(f"RoboSuite version: {data.attrs.get('repository_version', '?')}")
        print()

        demo_names = sorted(data.keys(), key=lambda n: int(n.split("_")[1]))
        print(f"Number of demonstrations: {len(demo_names)}")
        print()

        for name in demo_names:
            demo = data[name]
            n_steps = demo["states"].shape[0]
            print(
                f"  {name}: {n_steps} steps  "
                f"(states shape={demo['states'].shape}, actions shape={demo['actions'].shape})"
            )

        if demo_names:
            print()
            print(f"Example - first 5 actions from {demo_names[0]} (7 joint angles + gripper):")
            print(np.round(data[demo_names[0]]["actions"][:5], 3))


def replay(path, demo_name, control_freq=20, camera_names=("agentview", "robot0_eye_in_hand", "sideview"), save_video=None):
    """
    Replay a recorded demonstration in the RoboSuite viewer.

    In addition to the main RoboSuite viewer, the function displays the
    selected camera observations (agentview, robot0_eye_in_hand, and sideview)
    in a separate OpenCV window. The main env.render() viewer displays only
    one interactive camera and does not automatically display all cameras
    listed in camera_names.

    Args:
        path (str):
            Path to the HDF5 dataset.

        demo_name (str):
            Name of the demonstration to replay, e.g. "demo_1".

        control_freq (int):
            Playback frequency in Hz.

        camera_names (tuple or list or None):
            Names of the cameras whose observations should be displayed
            during replay.

        save_video (str or None):
            Optional output path for saving a video, e.g. "replay.mp4".
            When provided, the same combined camera view displayed through
            OpenCV is also written to the video file.

    The video is generated directly from the rendered camera frames rather
    than from screen capture. This avoids unrelated windows, notifications,
    or other desktop elements appearing in the recording and allows the
    resulting video to be viewed independently of RoboSuite.

    The replay procedure is based directly on
    robosuite/scripts/playback_demonstrations_from_hdf5.py and is extended
    with multi-camera visualization using
    env._get_observations(force_update=True). This is the same mechanism
    RoboSuite uses internally to refresh observations without calling
    env.step().
    """
    import json

    import cv2
    import robosuite.macros as macros
    macros.IMAGE_CONVENTION = "opencv"

    import robosuite as suite
    # pipeline/ contains hanoi_three_env.py -- add it to the import
    # path regardless of which directory this script is run from
    import os, sys
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "pipeline"))
    import hanoi_three_env 

    with h5py.File(path, "r") as f:
        env_info = json.loads(f["data"].attrs["env_info"])
        demo = f["data"][demo_name]
        model_xml = demo.attrs["model_file"]
        states = demo["states"][()]

    use_cameras = bool(camera_names)

    if save_video and not use_cameras:
        raise ValueError( "save_video requires at least one camera in camera_names, there are no camera frames to record.")

    env = suite.make(
        **env_info,
        has_renderer=True,
        has_offscreen_renderer=use_cameras,
        use_camera_obs=use_cameras,
        camera_names=list(camera_names) if use_cameras else None,
        camera_heights=256 if use_cameras else None,
        camera_widths=256 if use_cameras else None,
        ignore_done=True,
        control_freq=control_freq,
    )

    env.reset()

    # Restore the exact MJCF model saved with this demonstration.
    # edit_model_xml() applies RoboSuite's required XML preprocessing before the model is loaded into the simulation
    xml = env.edit_model_xml(model_xml) 
    env.reset_from_xml_string(xml)
    env.sim.reset()

    # Select the default viewer camera for the main RoboSuite window
    if getattr(env, "viewer", None) is not None:
        env.viewer.set_camera(0)

    print(f"Replaying {demo_name} - {len(states)} steps...")
    if use_cameras:
        print(f"Additional cameras in separate window: {list(camera_names)}")
    if save_video:
        print(f"Saving video to: {save_video}")

    # Initialize the video writer after receiving the first combined frame, since its exact dimensions depend on the selected camera configuration
    video_writer = None  

    for state in states:
        # Restore the recorded MuJoCo state instead of stepping the environment
        # This reproduces the exact robot and object configuration stored during the original demonstration
        env.sim.set_state_from_flattened(state)
        env.sim.forward()

        # Update the interactive RoboSuite viewer when using the MuJoCo viewer
        if env.renderer == "mjviewer":
            env.viewer.update()
        env.render()

        if use_cameras:
            #  Force-refresh camera observations without advancing the simulation
            obs = env._get_observations(force_update=True)
            tiles = []
            for cam in camera_names:
                key = f"{cam}_image"
                if key in obs:
                    tiles.append(cv2.cvtColor(obs[key], cv2.COLOR_RGB2BGR))
            if tiles:
                combined = cv2.hconcat(tiles)
                cv2.imshow("Replay - recorded cameras", combined)
                cv2.waitKey(1)

                if save_video:
                    if video_writer is None:
                        h, w = combined.shape[:2]
                        fourcc = cv2.VideoWriter_fourcc(*"mp4v")
                        video_writer = cv2.VideoWriter(save_video, fourcc, control_freq, (w, h))
                    video_writer.write(combined)

        # Match the playback speed to the recording/control frequency
        time.sleep(1.0 / control_freq)

    print("Replay finished.")
    if video_writer is not None:
        video_writer.release()
        print(f"Video saved to: {save_video}")
    if use_cameras:
        cv2.destroyAllWindows()
    env.close()


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python inspect_dataset.py path/to/demo.hdf5 [--replay demo_1] [--save_video video.mp4]")
        sys.exit(1)

    path = sys.argv[1]

    if "--replay" in sys.argv:
        idx = sys.argv.index("--replay")
        demo_name = sys.argv[idx + 1]

        save_video = None
        if "--save_video" in sys.argv:
            vidx = sys.argv.index("--save_video")
            save_video = sys.argv[vidx + 1]

        replay(path, demo_name, save_video=save_video)
    else:
        inspect(path)